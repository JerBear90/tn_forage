// Query Helpers
// ---------------------------------------------------------------------------

/**
 * Get all items with a `"pending"` sync status.
 *
 * @returns An array of pending {@link SyncQueueItem}s.
 */
export async function getPending(): Promise<SyncQueueItem[]> {
  return getByStatus('pending');
}

/**
 * Get all items with a `"failed"` sync status.
 *
 * @returns An array of failed {@link SyncQueueItem}s.
 */
export async function getFailed(): Promise<SyncQueueItem[]> {
  return getByStatus('failed');
}

/**
 * Get all items targeting a specific collection.
 *
 * @param collection - The collection name to filter by (e.g. `"trips"`).
 * @returns An array of {@link SyncQueueItem}s for that collection.
 */
export async function getByCollection(
  collection: string,
): Promise<SyncQueueItem[]> {
  const db = await getDB();
  return db.getAllFromIndex('syncQueue', 'by-collection', collection);
}

// ---------------------------------------------------------------------------
// Maintenance
// ---------------------------------------------------------------------------

/**
 * Remove all items with a `"done"` sync status from the queue.
 *
 * This is a housekeeping operation to keep the IndexedDB store lean.
 */
export async function clearDone(): Promise<void> {
  const db = await getDB();
  const tx = db.transaction('syncQueue', 'readwrite');
  const index = tx.store.index('by-syncStatus');

  let cursor = await index.openCursor(IDBKeyRange.only('done'));
  while (cursor) {
    await cursor.delete();
    cursor = await cursor.continue();
  }

  await tx.done;
}

/**
 * Reset failed items back to `"pending"` so they can be retried.
 *
 * Items whose `retryCount` has reached or exceeded `maxRetries` are left
 * in the `"failed"` state.
 *
 * @param maxRetries - Maximum number of retries allowed. Defaults to `3`.
 * @returns The number of items that were reset to pending.
 */
export async function retryFailed(maxRetries: number = 3): Promise<number> {
  const db = await getDB();
  const tx = db.transaction('syncQueue', 'readwrite');
  const index = tx.store.index('by-syncStatus');
  let resetCount = 0;

  let cursor = await index.openCursor(IDBKeyRange.only('failed'));
  while (cursor) {
    const item = cursor.value;
    if (item.retryCount < maxRetries) {
      item.syncStatus = 'pending';
      item.updatedAt = new Date().toISOString();
      await cursor.update(item);
      resetCount += 1;
    }
    cursor = await cursor.continue();
  }

  await tx.done;
  return resetCount;
}

