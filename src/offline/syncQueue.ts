/**
 * Retrieve all queue items matching a given sync status.
 *
 * @param status - The {@link SyncQueueStatus} to filter by.
 * @returns An array of matching {@link SyncQueueItem}s.
 */
async function getByStatus(status: SyncQueueStatus): Promise<SyncQueueItem[]> {
  const db = await getDB();
  return db.getAllFromIndex('syncQueue', 'by-syncStatus', status);
}

/**
 * Update the sync status of a queue item and refresh its `updatedAt` timestamp.
 *
 * @param localId - The local identifier of the queue item.
 * @param status  - The new {@link SyncQueueStatus}.
 */
async function updateStatus(
  localId: string,
  status: SyncQueueStatus,
): Promise<void> {
  const db = await getDB();
  const item = await db.get('syncQueue', localId);
  if (!item) return;

  item.syncStatus = status;
  item.updatedAt = new Date().toISOString();
  await db.put('syncQueue', item);
}
